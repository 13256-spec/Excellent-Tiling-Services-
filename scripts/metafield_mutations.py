#!/usr/bin/env python3
"""data/metafields/definitions.json -> data/metafields/mutations.graphql

Two mutation documents: one creates the new definitions, one updates the reused ones
(storefront access + pinning) so the theme and the Search & Discovery filters can read them.
Run each document once with the Admin GraphQL API (2026-10). Re-running the create document
on an existing key fails with "key is in use", which is harmless.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "data/metafields/definitions.json"
OUT = ROOT / "data/metafields/mutations.graphql"


def gql_str(s):
    return json.dumps(s)


def validations(v):
    if not v:
        return ""
    items = []
    for name, value in v.items():
        val = value if isinstance(value, str) else json.dumps(value)
        items.append("{ name: %s, value: %s }" % (gql_str(name), gql_str(val)))
    return ", validations: [%s]" % ", ".join(items)


def build(d):
    ns, owner, access = d["namespace"], d["owner_type"], d["storefront_access"]
    lines = ["# Generated by scripts/metafield_mutations.py from definitions.json. Do not edit by hand.", "",
             "mutation CreateHouseBrandMetafieldDefinitions {"]
    for i, m in enumerate(d["create"], 1):
        lines.append(
            "  c%d: metafieldDefinitionCreate(definition: { namespace: %s, key: %s, name: %s, type: %s, ownerType: %s, "
            "description: %s, pin: %s, access: { storefront: %s }%s }) { createdDefinition { id key } userErrors { field message code } }"
            % (i, gql_str(ns), gql_str(m["key"]), gql_str(m["name"]), gql_str(m["type"]), owner,
               gql_str(m.get("description", "")), "true" if m.get("pin") else "false", access,
               validations(m.get("validations"))))
    lines += ["}", "", "mutation UpdateReusedMetafieldDefinitions {"]
    for i, m in enumerate(d["reuse"], 1):
        if m["key"] in ("supplier", "lead_time"):
            continue  # internal fields stay admin-only
        lines.append(
            "  u%d: metafieldDefinitionUpdate(definition: { namespace: %s, key: %s, ownerType: %s, access: { storefront: %s }%s }) "
            "{ updatedDefinition { id key } userErrors { field message code } }"
            % (i, gql_str(ns), gql_str(m["key"]), owner, access, ", pin: true" if m.get("pin") else ""))
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    data = json.loads(SRC.read_text())
    text = build(data)
    OUT.write_text(text)
    # self-check: every create key appears exactly once, nothing reuses a key it also creates
    keys = [m["key"] for m in data["create"]]
    assert len(keys) == len(set(keys)), "duplicate create keys"
    assert not set(keys) & {m["key"] for m in data["reuse"]}, "key both reused and created"
    assert all(text.count('key: "%s"' % k) == 1 for k in keys)
    print("wrote", OUT.relative_to(ROOT), len(keys), "create,", text.count("metafieldDefinitionUpdate"), "update")

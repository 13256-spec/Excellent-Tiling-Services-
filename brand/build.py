#!/usr/bin/env python3
"""brand/tokens.json -> theme/assets/ets-tokens.css + brand/email.css

The theme file redeclares the --ets-* custom properties the storefront already uses, so changing a
value here changes every section, Horizon block and email that reads it. Run after editing tokens.json
and commit both outputs.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "brand/tokens.json").read_text())


def css_vars():
    v = []
    for k, val in T["color"].items():
        v.append(f"  --ets-{k}: {val};")
    v += ["  --ets-navy: var(--ets-ink);", "  --ets-accent: var(--ets-brass);"]  # aliases older sections use
    for k, f in T["finish"].items():
        if not k.startswith("_"):
            v.append(f"  --ets-finish-{k}: {f['hex']};")
    v += [f"  --ets-serif: {T['font']['serif']};", f"  --ets-sans: {T['font']['sans']};"]
    for k, val in T["type"].items():
        v.append(f"  --ets-t-{k}: {val};")
    for k, val in T["space"].items():
        name = {"gutter": "gutter", "sec": "sec", "max": "max"}.get(k, f"s-{k}")
        v.append(f"  --ets-{name}: {val};")
    for k, val in T["radius"].items():
        v.append(f"  --ets-r-{k}: {val};" if k != "md" else f"  --ets-r: {val};")
    v += [f"  --ets-shadow: {T['shadow']['sm']};", f"  --ets-shadow-lg: {T['shadow']['lg']};",
          f"  --ets-ease: {T['motion']['ease']};", f"  --ets-ease-out: {T['motion']['ease-out']};",
          # Horizon reads these for stock blocks (collection grid, product form, cart)
          "  --font-body--family: var(--ets-sans);", "  --font-subheading--family: var(--ets-sans);",
          "  --font-accent--family: var(--ets-sans);", "  --font-heading--family: var(--ets-serif);",
          f"  --font-heading--weight: {T['font']['heading-weight']};"]
    return v


def theme_css():
    return ("/* Generated by brand/build.py from brand/tokens.json. Do not edit; edit tokens.json and rebuild.\n"
            "   Loaded last from layout/theme.liquid so these values are the ones in effect. */\n"
            ":root {\n" + "\n".join(css_vars()) + "\n}\n")


def email_css():
    c, f, t = T["color"], T["font"], T["type"]
    return f"""/* Generated by brand/build.py from brand/tokens.json. Email-safe subset (hex colours, px sizes, web-safe
   font stacks with the brand fonts first). Paste inside the <style> of Shopify Settings -> Notifications ->
   Customer notifications -> Customize email templates, or a Klaviyo base template. */
body, .body {{ background: {c['bg-2']}; color: {c['ink']}; font-family: 'Manrope', {f['email-sans']}; font-size: {t['body']}; line-height: {t['line-body']}; }}
.container, .main {{ background: {c['bg']}; }}
h1, h2, .heading {{ font-family: 'Instrument Serif', {f['email-serif']}; font-weight: {f['heading-weight']}; color: {c['ink']}; line-height: {t['line-heading']}; }}
h1 {{ font-size: 32px; }}
h2 {{ font-size: 24px; }}
.eyebrow {{ font-size: {t['eyebrow']}; letter-spacing: {t['tracking-eyebrow']}; text-transform: uppercase; color: {c['brass']}; font-weight: 600; }}
a {{ color: {c['brass']}; }}
.button__text, .button, a.button {{ background: {c['ink']}; color: {c['white']}; border-radius: {T['radius']['pill']}; padding: 14px 26px; font-weight: 600; text-decoration: none; display: inline-block; }}
.muted, .footer, .disclaimer {{ color: {c['muted']}; font-size: {t['small']}; }}
hr, .rule {{ border: 0; border-top: 1px solid #E3E0D9; }}
.panel {{ background: {c['brass-soft']}; border-radius: {T['radius']['md']}; padding: 16px; }}
"""


if __name__ == "__main__":
    out1 = ROOT / "theme/assets/ets-tokens.css"
    out2 = ROOT / "brand/email.css"
    out1.write_text(theme_css())
    out2.write_text(email_css())
    css = out1.read_text()
    assert "--ets-ink: #15213A;" in css and "--ets-finish-brushed-brass" in css and css.count("{") == 1
    print("wrote", out1.relative_to(ROOT), "and", out2.relative_to(ROOT), f"({css.count('--ets-')} tokens)")
